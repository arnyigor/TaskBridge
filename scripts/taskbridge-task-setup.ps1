param(
  [Parameter(Mandatory = $true)][string]$Root,
  [Parameter(Mandatory = $true)][string]$Node
)
$ErrorActionPreference = 'Stop'

$root = (Resolve-Path -LiteralPath $Root).Path.TrimEnd('\')
$node = (Resolve-Path -LiteralPath $Node).Path
$local = Join-Path $root '.local'
$data = Join-Path $root 'data'
New-Item -ItemType Directory -Force -Path $local, $data | Out-Null
$watchdog = Join-Path $local 'taskbridge-watchdog.vbs'
$ui = Join-Path $local 'start-ui.cmd'
$exe = Join-Path $root 'clients\kmp\dist\TaskBridge\TaskBridge.exe'
$log = Join-Path $data 'watchdog.log'

# The watchdog is hidden: an InteractiveToken task with cmd.exe would flash a
# console every three minutes. wscript runs the same `ensure` with window 0.
# The command line is rendered by scripts/watchdog-vbs.mjs, whose exact output is
# executed by tests/watchdog-vbs.test.mjs: the old inline template was silently
# broken by cmd /c quote stripping (2026-11-22 outage).
& $Node (Join-Path $root 'scripts\watchdog-vbs.mjs') --root $root --node $node --log $log --out $watchdog
if ($LASTEXITCODE -ne 0) { throw 'Не удалось сгенерировать watchdog VBS.' }

# The UI launcher only waits for the privileged server and opens the window;
# it never starts the server itself, so the UI stays non-elevated (drag&drop).
$uiText = @"
@echo off
rem Generated by scripts\taskbridge-task-setup.ps1.
rem The server is owned by the scheduled task "TaskBridge" (elevated).
set "EXE=$exe"
for /l %%i in (1,1,180) do (
  powershell -NoProfile -Command "try{(New-Object Net.Sockets.TcpClient('127.0.0.1',8787)).Close();exit 0}catch{exit 1}" >nul 2>&1
  if not errorlevel 1 goto ready
  timeout /t 1 /nobreak >nul
)
:ready
if exist "%EXE%" start "" "%EXE%"
"@
Set-Content -LiteralPath $ui -Value $uiText -Encoding ASCII

$user = "$env:USERDOMAIN\$env:USERNAME"
$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument ('//B "' + $watchdog + '"')
$atLogon = New-ScheduledTaskTrigger -AtLogOn -User $user
# No -RepetitionDuration: an empty duration is how Task Scheduler spells
# "repeat indefinitely" (PT0S / MaxValue are rejected as out of range).
$everyThreeMinutes = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(1) `
  -RepetitionInterval (New-TimeSpan -Minutes 3)
$settings = New-ScheduledTaskSettingsSet `
  -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
  -MultipleInstances IgnoreNew -ExecutionTimeLimit ([TimeSpan]::Zero) `
  -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)
$principal = New-ScheduledTaskPrincipal -UserId $user -LogonType Interactive -RunLevel Highest
Register-ScheduledTask -TaskName 'TaskBridge' -Action $action `
  -Trigger @($atLogon, $everyThreeMinutes) -Settings $settings `
  -Principal $principal -Force | Out-Null

$startup = [Environment]::GetFolderPath('Startup')
$shell = New-Object -ComObject WScript.Shell
$link = $shell.CreateShortcut((Join-Path $startup 'TaskBridge.lnk'))
$link.TargetPath = $ui
$link.WorkingDirectory = $root
$link.Save()

$task = Get-ScheduledTask -TaskName 'TaskBridge'
$info = Get-ScheduledTaskInfo -TaskName 'TaskBridge'
Write-Host "Task:        $($task.TaskName)"
Write-Host "State:       $($task.State)"
Write-Host "RunLevel:    $($task.Principal.RunLevel)  (must be Highest)"
Write-Host "Triggers:    $($task.Triggers.Count)"
Write-Host "Next run:    $($info.NextRunTime)"
Write-Host "Watchdog:    $watchdog"
Write-Host "UI:          $ui"
